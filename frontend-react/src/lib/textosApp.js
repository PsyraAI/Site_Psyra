const POSICAO = { en: 0, zh: 1 };

export function traduzirDimensao(texto, idioma) {
  if (idioma === "pt" || !texto) return texto;
  return DIMENSOES[texto]?.[POSICAO[idioma]] ?? texto;
}

export function traduzirAcao(texto, idioma) {
  if (idioma === "pt" || !texto) return texto;
  return ACOES[texto]?.[POSICAO[idioma]] ?? texto;
}

/** Mês e ano por extenso no idioma (ex.: "outubro de 2026"). */
export function mesAno(idioma, data = new Date()) {
  const cfg = TEXTOS_APP[idioma] ?? TEXTOS_APP.pt;
  return new Intl.DateTimeFormat(cfg.locale, { month: "long", year: "numeric" }).format(data);
}

export function formatarData(iso, idioma) {
  if (!iso) return "";
  const cfg = TEXTOS_APP[idioma] ?? TEXTOS_APP.pt;
  const data = new Date(String(iso).replace(" ", "T") + (String(iso).includes("Z") || String(iso).includes("+") ? "" : "Z"));
  if (Number.isNaN(data.getTime())) return "";
  return new Intl.DateTimeFormat(cfg.locale, { day: "numeric", month: "short", year: "numeric" }).format(data);
}
